"use strict";

const byId = id => document.getElementById(id);
const video = byId("video");
const canvas = byId("overlay");
const drawing = canvas.getContext("2d");
const seek = byId("seek");
const status = byId("status");
const list = byId("candidates");
const detectButton = byId("detect");
const clipInput = byId("clip");
const resultsInput = byId("results");
const profile = byId("profile");
const labelInput = byId("label");
const exportLabels = byId("export-labels");
const labels = new Map();
const localServer = location.protocol === "http:" &&
  ["127.0.0.1", "courtvision.localhost"].includes(location.hostname);
const controls = [byId("play"), byId("back"), byId("forward"), seek];
const skeleton = [[5,6],[5,7],[7,9],[6,8],[8,10],[5,11],[6,12],[11,12],[11,13],[13,15],[12,14],[14,16]];

let clipFile;
let clipUrl;
let result;
let selected = -1;
let ready = false;
let matchVersion = 0;
let resultVersion = 0;
let currentFrame = 0;
let requestedFrame = null;
let videoFrames = new Map();

function validate(raw) {
  if (raw?.schema_version !== "0.1.0" || !Array.isArray(raw.frames) || !Array.isArray(raw.contacts)) {
    throw new Error("Choose a CourtVision contact result generated by the contacts command.");
  }
  const meta = raw.video;
  if (!(Number.isFinite(meta?.fps) && meta.fps > 0 &&
      Number.isInteger(meta.width) && meta.width > 0 &&
      Number.isInteger(meta.height) && meta.height > 0 &&
      Number.isInteger(meta.n_frames) && meta.n_frames > 0)) {
    throw new Error("The contact file has invalid video metadata.");
  }
  if (raw.frames.length !== meta.n_frames) {
    throw new Error("The contact file is missing pose frames.");
  }
  for (const [index, frame] of raw.frames.entries()) {
    if (frame?.index !== index || !Array.isArray(frame.players)) {
      throw new Error("The contact file has invalid frame records.");
    }
    for (const player of frame.players) {
      if (!Number.isInteger(player?.track_id) || !Array.isArray(player.bbox) ||
          player.bbox.length !== 4 || !player.bbox.every(Number.isFinite) ||
          !Array.isArray(player.keypoints) || player.keypoints.length !== 17 ||
          !player.keypoints.every(point => Array.isArray(point) && point.length === 3 &&
            point.every(Number.isFinite))) {
        throw new Error("The contact file has invalid pose coordinates.");
      }
    }
  }
  for (const event of raw.contacts) {
    if (!Number.isInteger(event?.start_frame) || !Number.isInteger(event.end_frame) ||
        event.start_frame < 0 || event.end_frame < event.start_frame ||
        event.end_frame >= meta.n_frames || !Array.isArray(event.track_ids) ||
        event.track_ids.length !== 2 || !event.track_ids.every(Number.isInteger) ||
        event.track_ids[0] >= event.track_ids[1] ||
        !Number.isInteger(event.hit_frames) || event.hit_frames < 1 ||
        event.hit_frames > event.end_frame - event.start_frame + 1) {
      throw new Error("The contact file has an invalid event interval.");
    }
  }
  return raw;
}

function disableReview() {
  ready = false;
  selected = -1;
  requestedFrame = null;
  labelInput.disabled = true;
  labelInput.value = "";
  video.pause();
  controls.forEach(control => { control.disabled = true; });
  list.querySelectorAll("button").forEach(button => {
    button.disabled = true;
    button.setAttribute("aria-pressed", "false");
  });
  drawing.clearRect(0, 0, canvas.width, canvas.height);
  byId("frame").textContent = "Frame —";
}

async function matchClip() {
  const version = ++matchVersion;
  disableReview();
  if (!clipFile || !result || video.readyState < 1) {
    status.textContent = clipFile && localServer
      ? "Run Detection or open saved results."
      : "Choose a clip and its contact JSON, or start the CourtVision server to run detection.";
    return;
  }
  const meta = result.video;
  if (video.videoWidth !== meta.width || video.videoHeight !== meta.height ||
      Math.abs(video.duration - meta.n_frames / meta.fps) > Math.max(0.25, 2 / meta.fps)) {
    status.textContent = "Video dimensions or duration differ from the contact file.";
    return;
  }
  let verified = false;
  if (meta.source_sha256 && globalThis.crypto?.subtle) {
    status.textContent = "Checking that this is the original clip…";
    try {
      const digest = await crypto.subtle.digest("SHA-256", await clipFile.arrayBuffer());
      const hex = [...new Uint8Array(digest)].map(byte => byte.toString(16).padStart(2, "0")).join("");
      if (version !== matchVersion) return;
      if (hex !== meta.source_sha256) {
        status.textContent = "This clip does not match the contact results.";
        return;
      }
      verified = true;
    } catch {
      if (version !== matchVersion) return;
    }
  }
  if (version !== matchVersion) return;
  if (!verified && meta.source && clipFile.name !== meta.source) {
    status.textContent = "The clip filename differs from the source in the contact results.";
    return;
  }
  ready = true;
  canvas.width = meta.width;
  canvas.height = meta.height;
  seek.max = meta.n_frames - 1;
  controls.forEach(control => { control.disabled = false; });
  list.querySelectorAll("button").forEach(button => { button.disabled = false; });
  status.textContent = verified ? "Source clip verified." : "Clip matched by name and video metadata.";
  drawAt(video.currentTime);
}

function drawAt(time) {
  if (!ready) return;
  const fps = result.video.fps;
  currentFrame = Math.max(0, Math.min(result.video.n_frames - 1, Math.floor(time * fps + 0.001)));
  seek.value = currentFrame;
  byId("frame").textContent = `Frame ${currentFrame} · ${time.toFixed(2)} s`;
  drawing.clearRect(0, 0, canvas.width, canvas.height);
  if (!byId("show-pose").checked) return;

  const event = result.contacts[selected];
  const highlight = event && currentFrame >= event.start_frame && currentFrame <= event.end_frame;
  drawing.font = `${Math.max(12, canvas.width / 64)}px system-ui`;
  for (const player of videoFrames.get(currentFrame)?.players ?? []) {
    const active = highlight && event.track_ids.includes(player.track_id);
    const [x1, y1, x2, y2] = player.bbox;
    drawing.strokeStyle = drawing.fillStyle = active ? "#ffc36d" : "#55e0c1";
    drawing.lineWidth = active ? 4 : 2;
    drawing.strokeRect(x1, y1, x2 - x1, y2 - y1);
    drawing.fillText(`#${player.track_id}`, x1, Math.max(16, y1 - 4));
    drawing.beginPath();
    for (const [a, b] of skeleton) {
      const [xa, ya, ca] = player.keypoints[a];
      const [xb, yb, cb] = player.keypoints[b];
      if (ca <= 0.3 || cb <= 0.3) continue;
      drawing.moveTo(xa, ya);
      drawing.lineTo(xb, yb);
    }
    drawing.stroke();
  }
}

function goTo(frame) {
  if (!ready) return;
  video.pause();
  requestedFrame = Math.max(0, Math.min(result.video.n_frames - 1, frame));
  seek.value = requestedFrame;
  // Seek inside the frame interval rather than exactly on a decoder boundary.
  video.currentTime = Math.min((requestedFrame + 0.2) / result.video.fps, video.duration);
}

function renderCandidates() {
  list.replaceChildren();
  byId("candidate-count").textContent = result.contacts.length
    ? `${result.contacts.length} candidates · Select one to jump to its start.`
    : "No candidates were detected with these settings. Try Broad search to review more possibilities.";
  result.contacts.forEach((event, index) => {
    const item = document.createElement("li");
    const button = document.createElement("button");
    button.disabled = true;
    button.setAttribute("aria-pressed", "false");
    button.textContent = `${(event.start_frame / result.video.fps).toFixed(2)} s · Tracks ${event.track_ids.join(" / ")} · Frames ${event.start_frame}–${event.end_frame} · ${event.hit_frames} hits`;
    button.addEventListener("click", () => {
      list.querySelector('[aria-pressed="true"]')?.setAttribute("aria-pressed", "false");
      button.setAttribute("aria-pressed", "true");
      selected = index;
      labelInput.disabled = false;
      labelInput.value = labels.get(index) ?? "";
      goTo(event.start_frame);
    });
    item.append(button);
    list.append(item);
  });
}

clipInput.addEventListener("change", event => {
  ++matchVersion;
  disableReview();
  if (clipUrl) URL.revokeObjectURL(clipUrl);
  clipFile = event.target.files[0];
  detectButton.disabled = !localServer || !clipFile;
  clipUrl = clipFile ? URL.createObjectURL(clipFile) : null;
  if (clipUrl) {
    status.textContent = "Loading video metadata…";
    video.src = clipUrl;
  } else {
    video.removeAttribute("src");
    video.load();
    status.textContent = "Choose a clip and its contact JSON.";
  }
});

function setResult(parsed) {
  labels.clear();
  exportLabels.disabled = true;
  result = parsed;
  videoFrames = new Map(result.frames.map(frame => [frame.index, frame]));
  renderCandidates();
  return matchClip();
}

resultsInput.addEventListener("change", async event => {
  const version = ++resultVersion;
  ++matchVersion;
  disableReview();
  result = null;
  labels.clear();
  exportLabels.disabled = true;
  videoFrames.clear();
  list.replaceChildren();
  byId("candidate-count").textContent = "Load contact JSON to see candidates.";
  const file = event.target.files[0];
  if (!file) {
    status.textContent = "Choose a clip and its contact JSON.";
    return;
  }
  status.textContent = "Reading contact results…";
  try {
    const parsed = validate(JSON.parse(await file.text()));
    if (version !== resultVersion) return;
    await setResult(parsed);
  } catch (error) {
    if (version === resultVersion) status.textContent = error.message;
  }
});

detectButton.addEventListener("click", async () => {
  if (!clipFile || !localServer) return;
  if (clipFile.size > 200 * 1024 * 1024) {
    status.textContent = "Choose an MP4 no larger than 200 MiB.";
    return;
  }
  ++matchVersion;
  disableReview();
  result = null;
  labels.clear();
  exportLabels.disabled = true;
  videoFrames.clear();
  list.replaceChildren();
  resultsInput.value = "";
  byId("candidate-count").textContent = "Waiting for detection results.";
  detectButton.disabled = clipInput.disabled = resultsInput.disabled = profile.disabled = true;
  status.textContent = "Sending clip to the local detector…";
  try {
    const endpoint = profile.value === "broad" ? "/detect?profile=broad" : "/detect";
    const response = await fetch(endpoint, {
      method: "POST",
      headers: { "Content-Type": "application/octet-stream" },
      body: clipFile,
    });
    if (!response.ok || !response.body) {
      throw new Error(`The local detector could not start (${response.status}).`);
    }
    const reader = response.body.getReader();
    const decoder = new TextDecoder();
    let pending = "";
    try {
      while (true) {
        const { value, done } = await reader.read();
        if (done) break;
        pending += decoder.decode(value, { stream: true });
        let end;
        while ((end = pending.indexOf("\n")) !== -1) {
          const event = JSON.parse(pending.slice(0, end));
          pending = pending.slice(end + 1);
          if (event.error) throw new Error(event.error);
          if (event.status) status.textContent = event.status;
          if (event.result) {
            event.result.video.source = clipFile.name;
            await setResult(validate(event.result));
            return;
          }
        }
      }
      throw new Error("The detector stopped before returning results.");
    } finally {
      await reader.cancel();
    }
  } catch (error) {
    status.textContent = `Detection failed: ${error.message}`;
    byId("candidate-count").textContent = "No candidate results available.";
  } finally {
    detectButton.disabled = clipInput.disabled = resultsInput.disabled = profile.disabled = false;
  }
});

labelInput.addEventListener("change", () => {
  if (!ready || selected < 0) return;
  if (labelInput.value) labels.set(selected, labelInput.value);
  else labels.delete(selected);
  exportLabels.disabled = !labels.size;
});

exportLabels.addEventListener("click", () => {
  if (!result || !labels.size) return;
  const payload = {
    version: 1,
    result,
    labels: Array.from(labels, ([event_index, label]) => ({ event_index, label })),
  };
  const url = URL.createObjectURL(new Blob([JSON.stringify(payload)], { type: "application/json" }));
  const link = document.createElement("a");
  link.href = url;
  link.download = "courtvision-review-labels.json";
  link.click();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
});

video.addEventListener("loadedmetadata", matchClip);
video.addEventListener("error", () => {
  ++matchVersion;
  disableReview();
  if (clipFile) status.textContent = "The browser could not play this video. Use an H.264 MP4 and regenerate its results.";
});
video.addEventListener("seeked", () => {
  requestedFrame = null;
  drawAt(video.currentTime);
});
if ("requestVideoFrameCallback" in video) {
  const onFrame = (_, metadata) => {
    drawAt(metadata.mediaTime);
    video.requestVideoFrameCallback(onFrame);
  };
  video.requestVideoFrameCallback(onFrame);
} else {
  video.addEventListener("timeupdate", () => drawAt(video.currentTime));
}
video.addEventListener("play", () => { byId("play").textContent = "Pause"; });
video.addEventListener("pause", () => { byId("play").textContent = "Play"; });
byId("play").addEventListener("click", async () => {
  if (!video.paused) {
    video.pause();
    return;
  }
  try {
    await video.play();
  } catch {
    status.textContent = "Video playback could not start.";
  }
});
byId("back").addEventListener("click", () => goTo((requestedFrame ?? currentFrame) - 1));
byId("forward").addEventListener("click", () => goTo((requestedFrame ?? currentFrame) + 1));
byId("show-pose").addEventListener("change", () => drawAt(currentFrame / (result?.video.fps ?? 1)));
seek.addEventListener("input", () => goTo(Number(seek.value)));
